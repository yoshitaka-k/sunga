use std::{fs, path::Path};

use crate::build::{collect_asset_stems, load_json, to_const_name, to_pascal};

/// assets/lang 内の JSON を定数として生成する
/// * `lang_dir` - 言語ディレクトリのパス
/// * `out_dir` - 出力ディレクトリのパス
pub(crate) fn generate_lang_generated(lang_dir: &Path, out_dir: &String) {
    let mut output = String::from("// @generated by build.rs — do not edit\n\n");

    // 土台となる構造体を en.json から取得して生成する
    let base = load_json(lang_dir, "en.json");
    let root = base.as_object().unwrap();

    let labels = root["labels"].as_object()
        .expect("en.json: 'labels' must be an object");

    output.push_str("#[allow(dead_code)]
pub struct Labels {
    pub code: &'static str,
    pub name: &'static str,\n");
    for (section, _fields) in labels {
        // setting_general → SettingGeneral
        let name = to_pascal(section);
        output.push_str(&format!("    pub {section}: {name},\n"));
    }
    output.push_str("}\n\n");

    // 構造体の定義を生成
    for (section, fields) in labels {
        // setting_general → SettingGeneral
        let name = to_pascal(section);
        output.push_str(&format!("#[allow(dead_code)]
pub struct {name} {{\n"));

        for key in fields.as_object().unwrap().keys() {
            output.push_str(&format!("    pub {key}: &'static str,\n"));
        }
        output.push_str("}\n");
    }
    output.push('\n');

    // 言語ファイルを生成
    let lang_files = collect_asset_stems(lang_dir, "json");
    for lang_file in &lang_files {
        let const_name = to_const_name(lang_file);
        let base = load_json(lang_dir, &format!("{lang_file}.json"));
        let root = base.as_object().unwrap();
        let labels = root["labels"].as_object().unwrap();

        output.push_str(&format!("#[allow(dead_code)]
pub const {const_name}: Labels = Labels {{\n"));

        let code = &root["code"].as_str().expect("code: must be a string");
        let name = &root["name"].as_str().expect("name: must be a string");
        output.push_str(&format!("    code: {:?},\n", code));
        output.push_str(&format!("    name: {:?},\n", name));

        for (section, fields) in labels {
            let pascal = to_pascal(section);
            output.push_str(&format!("    {section}: {pascal} {{"));

            for key in fields.as_object().unwrap().keys() {
                let value = fields.as_object().unwrap().get(key).unwrap();
                let s = value.as_str()
                    .unwrap_or_else(|| panic!("{}: must be a string", key));
                output.push_str(&format!(" {key}: {:?},", s));
            }
            output.push_str(" },\n");
        }

        output.push_str("};\n");
    }
    output.push('\n');

    // 言語リストを定義
    output.push_str("#[allow(dead_code)]
pub const LIST: &[&Labels] = &[");
    for (index, lang_file) in lang_files.iter().enumerate() {
        let const_name = to_const_name(lang_file);
        output.push_str(&format!("&{const_name}"));

        if index < lang_files.len() - 1 { output.push_str(", "); }
    }
    output.push_str("];\n");

    println!("cargo:warning=generated lang: {:?}", lang_files);

    let out_path = Path::new(out_dir).join("lang_generated.rs");
    fs::write(&out_path, output).expect("failed to write generated lang");
}
